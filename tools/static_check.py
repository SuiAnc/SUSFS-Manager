#!/usr/bin/env python3
"""Static checks for the standalone SUSFS manager.

This is not a substitute for compiling. It catches the classes of mistake that a port like this
actually makes -- a reference left behind from the upstream package, a resource that only exists in
one locale, an import that names a file which is not in the tree -- without needing a JDK, an
Android SDK or a network. Run it before every build.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "app" / "src" / "main"
JAVA = APP / "java"
RES = APP / "res"
OLD_PACKAGE = "me.weishu.kernelsu"
NEW_PACKAGE = "dev.susfs.manager"

# Generated by AGP from the resource tree, so there is no source file to point at.
GENERATED = {f"{NEW_PACKAGE}.R"}

failures: list[str] = []
notes: list[str] = []


def fail(message: str) -> None:
    failures.append(message)


def note(message: str) -> None:
    notes.append(message)


def kt_files() -> list[Path]:
    return sorted(JAVA.rglob("*.kt"))


def check_no_upstream_package() -> None:
    for path in kt_files() + sorted(ROOT.rglob("*.kts")):
        text = path.read_text(encoding="utf-8")
        if OLD_PACKAGE in text:
            fail(f"{path.relative_to(ROOT)}: still references {OLD_PACKAGE}")


def check_package_matches_path() -> None:
    for path in kt_files():
        first = next(
            (line for line in path.read_text(encoding="utf-8").splitlines() if line.startswith("package ")),
            None,
        )
        if first is None:
            fail(f"{path.relative_to(ROOT)}: no package declaration")
            continue
        declared = first.removeprefix("package ").strip()
        relative = path.parent.relative_to(JAVA)
        expected = ".".join(relative.parts)
        if declared != expected:
            fail(f"{path.relative_to(ROOT)}: package {declared} does not match path {expected}")


def check_internal_imports_resolve() -> None:
    """Every `import dev.susfs.manager.X.Y` must name a declaration that exists."""
    declared: set[str] = set()
    for path in kt_files():
        text = path.read_text(encoding="utf-8")
        package = re.search(r"^package (\S+)", text, re.M)
        if not package:
            continue
        prefix = package.group(1)
        for match in re.finditer(
            r"^[ \t]*(?:@\w+[^\n]*\n[ \t]*)*"
            r"(?:(?:public|internal|private|protected|abstract|open|sealed|data|enum|value|"
            r"annotation|inline|fun|operator|infix|external|lateinit|const|suspend|override|"
            r"tailrec|vararg|noinline|crossinline|actual|expect)\s+)*"
            r"(?:class|object|interface|fun|val|var|typealias)\s+([A-Za-z_]\w*)",
            text,
            re.M,
        ):
            declared.add(f"{prefix}.{match.group(1)}")

    for path in kt_files():
        for match in re.finditer(
            r"^import (dev\.susfs\.manager\.[A-Za-z_][\w.]*)$",
            path.read_text(encoding="utf-8"),
            re.M,
        ):
            symbol = match.group(1)
            if symbol.endswith(".*"):
                continue
            if symbol in declared or symbol in GENERATED:
                continue
            # A nested declaration (`Outer.Inner`) resolves when the outer type is declared.
            if any(symbol.startswith(d + ".") for d in declared):
                continue
            fail(f"{path.relative_to(ROOT)}: import {symbol} does not resolve to a declaration")


def string_names(path: Path) -> set[str]:
    return set(re.findall(r'<string name="([^"]+)"', path.read_text(encoding="utf-8")))


def check_strings_used_are_defined() -> None:
    defined: set[str] = set()
    for path in RES.rglob("*.xml"):
        if path.parent.name == "values" or path.parent.name.startswith("values-"):
            defined |= string_names(path)

    used: set[str] = set()
    for path in kt_files():
        used |= set(re.findall(r"R\.string\.(\w+)", path.read_text(encoding="utf-8")))

    for name in sorted(used - defined):
        fail(f"R.string.{name} is used but not defined in any values/ file")


def check_locale_parity() -> None:
    base = RES / "values" / "susfs.xml"
    if not base.exists():
        fail("res/values/susfs.xml is missing")
        return
    reference = string_names(base)
    for locale_dir in sorted(p for p in RES.iterdir() if p.name.startswith("values-")):
        path = locale_dir / "susfs.xml"
        if not path.exists():
            fail(f"{locale_dir.name}: susfs.xml is missing")
            continue
        translated = string_names(path)
        for name in sorted(reference - translated):
            fail(f"{locale_dir.name}: susfs.xml is missing {name}")
        for name in sorted(translated - reference):
            fail(f"{locale_dir.name}: susfs.xml has extra {name}")


def check_manifest() -> None:
    manifest = APP / "AndroidManifest.xml"
    if not manifest.exists():
        fail("AndroidManifest.xml is missing")
        return
    text = manifest.read_text(encoding="utf-8")
    if 'android:name=".SusfsApplication"' not in text:
        fail("AndroidManifest.xml does not declare .SusfsApplication")
    if ".ui.MainActivity" not in text:
        fail("AndroidManifest.xml does not declare .ui.MainActivity")

    # A leading dot is relative to the manifest package (the app namespace), not to the source root.
    package_root = JAVA / Path(*NEW_PACKAGE.split("."))
    for cls in re.findall(r'android:name="\.([\w.]+)"', text):
        path = package_root / Path(*cls.split(".")).with_suffix(".kt")
        if not path.exists():
            fail(f"AndroidManifest.xml names .{cls} but {path.relative_to(ROOT)} does not exist")

    for ref in re.findall(r"@(mipmap|drawable|color|style|string)/([\w.]+)", text):
        kind, name = ref
        if kind == "mipmap":
            if not list(RES.rglob(f"{name}.xml")):
                fail(f"AndroidManifest.xml references @mipmap/{name}, which is not defined")
        elif kind == "drawable":
            if not list(RES.rglob(f"{name}.xml")):
                fail(f"AndroidManifest.xml references @drawable/{name}, which is not defined")
        elif kind in ("style", "string"):
            found = False
            for candidate in RES.rglob("*.xml"):
                if candidate.parent.name == "values" or candidate.parent.name.startswith("values-"):
                    body = candidate.read_text(encoding="utf-8")
                    pattern = rf'<style name="{name}"' if kind == "style" else rf'<string name="{name}"'
                    if re.search(pattern, body):
                        found = True
                        break
            if not found:
                fail(f"AndroidManifest.xml references @{kind}/{name}, which is not defined")


def check_bundled_ksud() -> None:
    """The app execs `libksud.so` out of its own native library dir, so it must be bundled.

    This is the failure that produced `error: unrecognized subcommand 'susfs'`: without the payload
    the app falls back to whatever `ksud` the device happens to expose, and every stock KernelSU or
    KernelSU-Next build rejects the subcommand. Catching its absence here is much cheaper than
    discovering it on a phone.
    """
    path = JAVA / "dev" / "susfs" / "manager" / "data" / "susfs" / "SusfsRepository.kt"
    text = path.read_text(encoding="utf-8")
    expected = 'ksuApp.applicationInfo.nativeLibraryDir + "/libksud.so"'
    if expected not in text:
        fail("SusfsRepository.kt no longer resolves the bundled libksud.so from nativeLibraryDir")

    payload = APP / "jniLibs" / "arm64-v8a" / "libksud.so"
    if not payload.exists():
        note(
            "app/src/main/jniLibs/arm64-v8a/libksud.so is absent: build ksud from the FinaSU tree "
            "and copy it in before assembling, or the SUSFS subcommand will be missing at runtime"
        )
    elif payload.stat().st_size < 100_000:
        fail(f"{payload.relative_to(ROOT)} is only {payload.stat().st_size} bytes; that is not ksud")


def check_application_publishes_ksu_app() -> None:
    """`ksuApp` must exist and be assigned, or every SUSFS command fails to find the payload."""
    path = JAVA / "dev" / "susfs" / "manager" / "SusfsApplication.kt"
    text = path.read_text(encoding="utf-8")
    if not re.search(r"^lateinit var ksuApp:", text, re.M):
        fail("SusfsApplication.kt does not declare the global `lateinit var ksuApp`")
    if not re.search(r"^\s*ksuApp = this", text, re.M):
        fail("SusfsApplication.kt never assigns ksuApp in onCreate")


def check_no_stray_placeholders() -> None:
    for path in kt_files():
        text = path.read_text(encoding="utf-8")
        for marker in ("TODO(", "FIXME", "GlobalScope"):
            if marker in text:
                fail(f"{path.relative_to(ROOT)}: contains {marker}")


def main() -> int:
    checks = [
        check_no_upstream_package,
        check_package_matches_path,
        check_internal_imports_resolve,
        check_strings_used_are_defined,
        check_locale_parity,
        check_manifest,
        check_no_stray_placeholders,
        check_bundled_ksud,
        check_application_publishes_ksu_app,
    ]
    for check in checks:
        check()

    if failures:
        print(f"FAIL ({len(failures)})")
        for message in failures:
            print(f"  - {message}")
        return 1

    sources = kt_files()
    total = sum(len(p.read_text(encoding="utf-8").splitlines()) for p in sources)
    print(f"ok: {len(sources)} Kotlin files, {total} lines; all checks passed")
    for message in notes:
        print(f"  note: {message}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
